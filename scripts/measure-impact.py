def execute(command, output, timing):
    with output.open('w') as stdout, timing.with_suffix('.stderr').open('w') as stderr:
        subprocess.run(['/usr/bin/time', '-f', '%e\t%M', '-o', str(timing), *map(str, command)], stdout=stdout, stderr=stderr, check=True)
    elapsed, rss = timing.read_text().split()
    return {'seconds': float(elapsed), 'rss_kib': int(rss)}


def rows(path):
    return [json.loads(line) for line in path.read_text().splitlines()]


def dump(bins, work):
    """The rows of work/refs.pack, through refs.jsonl, untimed: the stages read the pack."""
    with (work / 'refs.jsonl').open('w') as stdout:
        subprocess.run([str(bins / 'sf-impact-extract'), '--dump', str(work / 'refs.pack')], stdout=stdout, check=True)
    return rows(work / 'refs.jsonl')


def convention(refs, changed):
    classes = {r['symbol'].lower() for r in refs if r['row'] == 'declaration' and r['type'] == 'class'}
    tests = {r['symbol'].lower(): r['symbol'] for r in refs if r['row'] == 'declaration' and r['type'] == 'class' and r['is_test']}
    owners = set()
    for row in changed:
        if row['row'] != 'symbol' or row['type'] not in ['class', 'method', 'constructor', 'field', 'enum_value']:
            continue
        name = row['symbol'].split('(')[0].lower()
        while name and name not in classes:
            name = name.rsplit('.', 1)[0] if '.' in name else ''
        if name:
            owners.add(name)
    return sorted({tests[name + suffix] for name in owners for suffix in ['test', 'tests', '_test', '_tests'] if name + suffix in tests})


def symbol_convention(refs, symbols):
    queries = {name.lower() for name in symbols}
    matches = []
    for row in refs:
        if row['row'] != 'declaration':
            continue
        name = row['symbol'].lower()
        bare = name.split('(')[0]
        if queries & {name, bare, bare.rsplit('.', 1)[-1]}:
            matches.append(dict(row, row='symbol'))
    return convention(refs, matches)


def summarize(path, baseline, total, timings, **identity):
    doc = json.loads(path.read_text())
    selected = {t['symbol']: t['reasons'] for t in doc['tests']}
    possible = {t['symbol']: t['reasons'] for t in doc['possible']}
    assert set(baseline) <= selected.keys(), (identity, set(baseline) - selected.keys())
    assert not selected.keys() & possible.keys(), identity
    return dict(identity, seeds=len(doc['seeds']), total_tests=total, convention=baseline, selected=selected, possible=possible,
                additional=sorted(selected.keys() - set(baseline)), confidence=doc['confidence'],
                gaps=dict(collections.Counter(g['reason'] for g in doc['gaps'])),
                diagnostics=doc['diagnostics'], timings=timings, output_bytes=path.stat().st_size)


def checkout(source, directory, head):
    if not directory.exists():
        subprocess.run(['git', 'clone', '--quiet', '--shared', '--no-checkout', str(source), str(directory)], check=True)
    subprocess.run(['git', '-C', str(directory), '-c', 'advice.detachedHead=false', 'checkout', '--quiet', head], check=True)


def summary_table(reports):
    lines = ['# Impact measurements', '',
             'Generated by `scripts/measure-impact.py`; range commits are pinned in `reconcile-changed.tsv`.',
             'Default depth 2; suffixes Test, Tests, _Test, _Tests; unpackaged tests included. Possible is disjoint from selected.',
             'First-hop member text needs same-file owner/enclosing/dispatch-type evidence; otherwise it is possible. Uncalled method seeds follow parsed owner entries.',
             'GNU time wall seconds and peak RSS per impact process; sequential release runs. Full stage timings, names and reasons are in the generated results.json.', '',
             '| Range | Seeds | Convention | Selected / all | Possible | Extract s | Impact s | RSS MiB | JSON MB |',
             '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for r in reports:
        t = r['timings']
        lines.append(f"| {r['range']} | {r['seeds']} | {len(r['convention'])} | {len(r['selected'])} / {r['total_tests']} | {len(r['possible'])} | {t['extract']['seconds']:.2f} | {t['impact']['seconds']:.2f} | {t['impact']['rss_kib']/1024:.1f} | {r['output_bytes']/1e6:.2f} |")
    lines += ['', 'Large release/hub changes can legitimately select most tests. Ordinary changes should not expand through enclosing types or textual chains.',
              'NPSP rows use a pinned 1/5/10/20/40-class sample at ' + NPSP_COMMIT + '.',
              'Known gaps: instance-field reads missing from extraction; a changed.jsonl without its provenance row is refused, so an empty file is no longer taken for an empty diff.', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bin-dir', required=True, type=Path)
    parser.add_argument('--clone', required=True, action='append', help='NebulaLogger=/path, apex-rollup=/path, NPSP=/path')
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    bins, out = args.bin_dir.resolve(), args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    clones = {name: Path(path).resolve() for name, path in (entry.split('=', 1) for entry in args.clone)}
    reports = []
    with (HERE / 'reconcile-changed.tsv').open() as f:
        ranges = list(csv.DictReader(f, delimiter='\t'))
    for row in ranges:
        work = out / row['range']; work.mkdir(exist_ok=True)
        tree = work / 'tree'; checkout(clones[row['corpus']], tree, row['head'])
        timings = {}
        timings['extract'] = execute([bins / 'sf-impact-extract', '--root', tree], work / 'refs.pack', work / 'extract.time')
        timings['delta'] = execute([bins / 'sf-impact-delta', '--root', tree, '--base', row['base'], '--head', row['head']], work / 'delta.jsonl', work / 'delta.time')
        timings['changed'] = execute([bins / 'sf-impact-changed', '--refs', work / 'refs.pack', '--delta', work / 'delta.jsonl'], work / 'changed.jsonl', work / 'changed.time')
        timings['impact'] = execute([bins / 'sf-impact-tests', '--refs', work / 'refs.pack', '--changed', work / 'changed.jsonl'], work / 'impact.json', work / 'impact.time')
        refs = dump(bins, work)
        total = sum(r['row'] == 'declaration' and r['type'] == 'class' and r['is_test'] for r in refs)
        baseline = convention(refs, rows(work / 'changed.jsonl'))
        reports.append(summarize(work / 'impact.json', baseline, total, timings, **row))
        print(row['range'], 'selected', len(reports[-1]['selected']), 'possible', len(reports[-1]['possible']), timings['impact'], flush=True)
    work = out / 'NPSP'; work.mkdir(exist_ok=True)
    tree = work / 'tree'; checkout(clones['NPSP'], tree, NPSP_COMMIT)
    extraction = execute([bins / 'sf-impact-extract', '--root', tree], work / 'refs.pack', work / 'extract.time')
    refs = dump(bins, work)
    total = sum(r['row'] == 'declaration' and r['type'] == 'class' and r['is_test'] for r in refs)
    for n in [1, 5, 10, 20, 40]:
        output = work / f'impact-{n}.json'
        timing = execute([bins / 'sf-impact-tests', '--refs', work / 'refs.pack', '--symbol', *NPSP_SYMBOLS[:n]], output, work / f'impact-{n}.time')
        baseline = symbol_convention(refs, NPSP_SYMBOLS[:n])
        reports.append(summarize(output, baseline, total, {'extract': extraction, 'impact': timing}, range=f'NPSP-{n}', head=NPSP_COMMIT, symbols=NPSP_SYMBOLS[:n]))
        print(f'NPSP-{n}', 'selected', len(reports[-1]['selected']), 'possible', len(reports[-1]['possible']), timing, flush=True)
    (out / 'results.json').write_text(json.dumps(reports, indent=2) + '\n')
    (out / 'summary.md').write_text(summary_table(reports))


if __name__ == '__main__':
    main()
